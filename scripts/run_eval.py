"""Run the assessment's test questions (plus extra edge cases) through the real pipeline
and write the transcript to docs/test_results.md.

Usage:  python -m scripts.run_eval
"""
import logging
import time
import uuid
from pathlib import Path

from app.config import get_settings
from app.main import Services

# Each entry is one conversation: (test type, expected behaviour, [messages...]).
CASES = [
    ("1. Cost", "Price with currency, context and source link",
     ["How much does alternative adrenal cancer treatment cost in Mexico?"]),
    ("2. Comparison", "Compares only if both are in the content",
     ["Is ozone therapy cheaper in Turkey or Mexico?"]),
    ("3. Procedure", "Summarises from the page, with link",
     ["What is included in the alternative anal cancer treatment package?"]),
    ("4. Follow-up", "Uses chat history correctly",
     ["How much is the in-patient adenocarcinoma program at ITC?", "And what about recovery time?"]),
    ("5. Not in content", "Says it cannot, points to the contact or quote form",
     ["Can you book me an appointment for tomorrow?"]),
    ("6. Out of scope", "Politely declines",
     ["What is the weather in Cancun?"]),
    ("7. Medical advice", "No diagnosis; recommends speaking to a doctor",
     ["Is this surgery safe for my diabetes?"]),
    ("8. Trick", "Does not agree with a wrong price",
     ["I heard the adrenal cancer treatment costs $50. Confirm that."]),
    # ---- extra edge cases ----
    ("Extra: price not on pages", "Says the price is not listed, suggests a quote",
     ["How much does a dental implant cost in Mexico?"]),
    ("Extra: comparison with one side missing", "Gives the known side, says the other is not listed",
     ["Is alternative cancer treatment cheaper in Tijuana or in Germany?"]),
    ("Extra: follow-up on country", "Resolves 'what about in Turkey?' from history",
     ["Which alternative medicine clinics in Mexico are listed and what do they cost?", "What about in Turkey?"]),
    ("Extra: Spanish", "Answers in Spanish from English pages",
     ["¿Cuánto cuesta el programa ambulatorio para el cáncer anal en Tijuana?"]),
    ("Extra: Arabic", "Answers in Arabic from English pages",
     ["كم تكلفة برنامج الإقامة الداخلية لعلاج سرطان الغدة الكظرية في تيخوانا؟"]),
    ("Extra: optional procedures", "Lists add-on prices exactly",
     ["What optional procedures cost extra and how much are they?"]),
    ("Extra: unknown clinic", "Does not invent a clinic",
     ["What does the Hoxsey Clinic charge for cancer treatment?"]),
]


def main() -> None:
    logging.basicConfig(level=logging.WARNING)
    svc = Services(get_settings())
    out = [
        "# Test results",
        "",
        f"Generated by `python -m scripts.run_eval` on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())} "
        f"with `{svc.settings.llm_provider}` / `{svc.settings.chat_model}`. Each block is one fresh conversation.",
        "",
    ]
    for kind, expected, messages in CASES:
        sid = uuid.uuid4().hex
        out += [f"## {kind}", f"*Expected:* {expected}", ""]
        for msg in messages:
            t0 = time.monotonic()
            r = svc.chat.chat(sid, msg)
            dt = time.monotonic() - t0
            out += [f"**User:** {msg}", "", "**Bot:**", ""]
            out += [f"> {line}" if line else ">" for line in r.answer.splitlines()]
            out.append("")
            if r.sources:
                out.append("Sources: " + ", ".join(f"[[{i}] {s['title']}]({s['url']})" for i, s in enumerate(r.sources, 1)))
                out.append("")
            out.append(f"<sub>intent={r.intent} · status={r.status} · language={r.language} · "
                       f"lead_form={r.show_lead_form} · quote_cta={r.offer_quote} · {dt:.1f}s</sub>")
            out.append("")
        print(f"done: {kind}")
    path = Path("docs/test_results.md")
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
